export type ClasprcFormat = 'v3' | 'v2' | 'v1-global';

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

export function detectClasprcFormat(raw: string): ClasprcFormat {
  let parsed: unknown;
  try {
    parsed = JSON.parse(raw) as unknown;
  } catch {
    throw new Error('clasprc cannot be parsed as JSON.');
  }

  if (isRecord(parsed)) {
    const tokens = parsed.tokens;
    if (isRecord(tokens) && tokens.default) {
      return 'v3';
    }

    if (parsed.token && parsed.oauth2ClientSettings) {
      return 'v2';
    }

    if (parsed.access_token) {
      return 'v1-global';
    }
  }

  throw new Error(
    'Please provide the contents of the `.clasprc.json` file generated by `clasp login` unchanged.'
  );
}
