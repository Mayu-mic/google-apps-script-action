import { describe, expect, test } from '@jest/globals';

import { detectClasprcFormat } from '../src/auth/clasprcFormat';

describe('detectClasprcFormat', () => {
  test('detects v3 clasprc format', () => {
    const raw = '{"tokens":{"default":{"refresh_token":"x"}}}';

    expect(detectClasprcFormat(raw)).toBe('v3');
  });

  test('detects v2 clasprc format', () => {
    const raw =
      '{"token":{"access_token":"x","refresh_token":"y"},"oauth2ClientSettings":{"clientId":"c","clientSecret":"s"},"isLocalCreds":false}';

    expect(detectClasprcFormat(raw)).toBe('v2');
  });

  test('prioritizes v2 over v1-global when both fields coexist', () => {
    const raw =
      '{"token":{"access_token":"x"},"oauth2ClientSettings":{"clientId":"c","clientSecret":"s"},"access_token":"legacy"}';

    expect(detectClasprcFormat(raw)).toBe('v2');
  });

  test('detects v1-global clasprc format', () => {
    const raw = '{"access_token":"x","refresh_token":"y"}';

    expect(detectClasprcFormat(raw)).toBe('v1-global');
  });

  test('prioritizes v3 when v3 and v2 fields coexist', () => {
    const raw =
      '{"tokens":{"default":{"refresh_token":"x"}},"token":{"access_token":"x"},"oauth2ClientSettings":{"clientId":"c","clientSecret":"s"}}';

    expect(detectClasprcFormat(raw)).toBe('v3');
  });

  test('throws when clasprc is not valid JSON', () => {
    expect(() => detectClasprcFormat('{invalid')).toThrow(
      'cannot be parsed as JSON'
    );
  });

  test('throws when clasprc has no recognized format', () => {
    expect(() => detectClasprcFormat('{}')).toThrow(
      'Please provide the contents of the `.clasprc.json` file generated by `clasp login` unchanged'
    );
  });

  test('rejects a JSON array as an unrecognized format', () => {
    expect(() => detectClasprcFormat('[]')).toThrow(
      'Please provide the contents of the `.clasprc.json` file generated by `clasp login` unchanged'
    );
  });
});
